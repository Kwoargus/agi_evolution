def generate_node_data(name, use_llm=True):
    if use_llm:
        prompt = f"""
Ты — эксперт по техническим системам и инженерии. 
Для концептуального узла «{name}» сгенерируй:
- краткое описание (1–2 предложения),
- список свойств (ключевые характеристики, 3–5 пунктов).

Ответ должен быть в формате JSON:
{{"description": "...", "properties": ["свойство1", "свойство2", ...]}}
"""
        try:
            response = ollama.chat(
                model='qwen2.5:7b',
                messages=[{'role': 'user', 'content': prompt}],
                options={'temperature': 0.3}
            )
            content = response['message']['content'].strip()
            json_match = re.search(r'\{.*\}', content, re.DOTALL)
            if json_match:
                return json.loads(json_match.group())
        except Exception as e:
            print(f"⚠️ Ошибка LLM для {name}: {e}")
    return {
        "description": f"Концептуальный узел: {name}",
        "properties": ["компонент технической системы"]
    }

def main():
    print(f"Найдено {len(MISSING_NODES)} отсутствующих узлов.")

    try:
        with open("name_to_id.json", "r", encoding="utf-8") as f:
            existing = json.load(f)
        print(f"Загружен существующий словарь ({len(existing)} записей).")
    except:
        existing = {}

    to_add = [n for n in MISSING_NODES if n not in existing]
    if not to_add:
        print("Все узлы уже добавлены.")
        return

    print(f"Добавляем {len(to_add)} узлов...")
    insert_statements = []

    for name in to_add:
        node_id = str(uuid.uuid4())
        data = generate_node_data(name, use_llm=True)
        description = data.get('description', f'Узел: {name}')
        properties = data.get('properties', [])
        properties_json = json.dumps(properties, ensure_ascii=False)

        insert_sql = f"""
INSERT INTO agi_evolution.knowledge_nodes (id, name, node_type, properties, description, embedding, parameters, metadata, created_at, updated_at, theme_id)
VALUES (
    '{node_id}',
    '{name.replace("'", "''")}',
    'CONCEPT',
    '{{"properties": {properties_json}}}'::jsonb,
    '{description.replace("'", "''")}',
    NULL,
    '{{}}'::jsonb,
    '{{}}'::jsonb,
    NOW(),
    NOW(),
    NULL
);
"""
        insert_statements.append(insert_sql)
        existing[name] = node_id
        print(f"Сгенерирован узел: {name} -> {node_id}")
        time.sleep(0.3)

    with open("insert_missing_nodes.sql", "w", encoding="utf-8") as f:
        f.write("BEGIN;\n")
        f.write("\n".join(insert_statements))
        f.write("\nCOMMIT;\n")

    with open("name_to_id.json", "w", encoding="utf-8") as f:
        json.dump(existing, f, ensure_ascii=False, indent=2)

    print(f"✅ Сгенерировано {len(insert_statements)} INSERT-запросов.")
    print("✅ Сохранено в insert_missing_nodes.sql и name_to_id.json")

if __name__ == "__main__":
    main()